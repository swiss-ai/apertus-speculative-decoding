#!/usr/bin/env python3
"""Domain drafters (A3), EAGLE grid: write one train config per arm.

Every arm repeats the bounded adaptation recipe that qualified in serving
(adapt-mult-n8k-r0: warm start from EAGLE e10 thinking-off, 32 rows/step on one
node, constant LR 3e-5 after 19 warmup steps, 384 steps = 12,288 rows, seed 1).
Only the training file changes. Each run evaluates its own domain dev set
(eval_data) and every other domain dev set plus 512 OPB held-out rows
(extra_eval), so the step-0 eval is the e10 row and the final eval is the
arm's row of the transfer matrix.

    python3 methods/eagle/launch/domain/make-configs.py   # rewrites configs/8b/domain/
"""

from __future__ import annotations

from pathlib import Path

DOMAINS = ("math", "code", "chat", "summarization", "multilingual", "structured")
ARMS = (*DOMAINS, "mixed")
DATA = "/iopsstor/scratch/cscs/faruk_zahiragic/spec-exp-data/domain-drafters"
ROOT = f"{DATA}/eagle"
INIT = f"{DATA}/init/eagle-e10-thinkoff-hf"
OPB = f"{DATA}/opb/heldout.jsonl"
OUT = Path(__file__).resolve().parents[2] / "configs" / "8b" / "domain"


def config(arm: str, *, pilot: bool = False) -> str:
    traces = f"{DATA}/traces/pilot" if pilot else f"{DATA}/traces"
    mixed = f"{ROOT}/mixed/train-n8000.jsonl"
    train = mixed if arm == "mixed" else f"{traces}/{arm}/train.jsonl"
    own = "math" if arm == "mixed" else arm  # mixed: math dev is eval_data, the rest extra
    extra = "\n".join(
        f"    - name: {d}\n      data: [{traces}/{d}/dev.jsonl]" for d in DOMAINS if d != own
    )
    steps, warmup, interval, save = (4, 0.25, 2, 4) if pilot else (384, 0.05, 64, 128)
    name = f"domain-{arm}-pilot" if pilot else f"domain-{arm}-n8k"
    return f"""# Domain drafters (A3), EAGLE arm "{arm}"{" (pilot smoke)" if pilot else ""}.
# Generated by methods/eagle/launch/domain/make-configs.py; do not edit by hand.
# Recipe = adapt-mult-n8k-r0 (drafter-updates); only the training file differs.
pipeline: rollout
stage: 8b

model:
  contract: targets/8b/contract.json
  algorithm: eagle31
  draft_model_config: methods/eagle/configs/8b/draft-e31-config.json
  freeze_lm_head: true
  share_target_embedding: true
  # Published e10 export (HF faruk-zahiragic/Apertus-v1.5-8B-EAGLE3.1-e10-thinking-off
  # @4c9d4c9e, SHA256SUMS verified); the trainer checkpoint was scratch-cleaned.
  init_from: {INIT}

dataset:
  features: online
  data_root: {ROOT}
  train_data:
    - {train}
  eval_data: [{traces}/{own}/dev.jsonl]
  extra_eval:
{extra}
    - name: opb
      data: [{OPB}]
      limit: {16 if pilot else 512}
  max_seq_length: 8192
  teacher_batch_tokens: 32768

training:
  attention_backend: sdpa
  loss_type: forward_kl
  ttt_length: 7
  micro_batch_size: 1
  rows_per_step: 32
  data_parallel: 4
  micro_batch_tokens: 8192
  gradient_checkpointing: adaptive
  checkpoint_free_width: 4096
  checkpoint_free_tokens: 8192
  learning_rate: 3.0e-5
  warmup_ratio: {warmup}
  max_grad_norm: 0.5
  weight_decay: 0.0
  lr_decay_style: constant
  min_lr: 0.0
  lr_total_steps: {steps}
  num_train_steps: {steps}
  num_epochs: 1000
  eval_interval: {interval}
  save_interval: {save}
  resume_interval: {save}
  stop_after_evals_without_improvement: 0
  stop_margin_s: 600
  seed: 1

export:
  checkpoint: final

output_root: {ROOT}/runs
head_root: {ROOT}/heads
run_name: {name}
"""


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for arm in ARMS:
        (OUT / f"domain-{arm}-n8k.yaml").write_text(config(arm))
    (OUT / "domain-pilot-smoke.yaml").write_text(config("math", pilot=True))
    # Pipeline smoke that needs no domain traces: start from the e10 export and
    # take 4 steps on OPB held-out rows (eval-only data, never a training arm).
    smoke = config("math", pilot=True)
    smoke = smoke.replace(f"{DATA}/traces/pilot/math/train.jsonl", OPB)
    head, _, tail = smoke.partition("  eval_data:")
    tail = tail.split("  max_seq_length:", 1)[1]
    smoke = (head + f"  eval_data: [{OPB}]\n  eval_limit: 16\n  max_seq_length:" + tail).replace(
        "domain-math-pilot", "domain-export-smoke"
    )
    (OUT / "domain-export-smoke.yaml").write_text(smoke)


if __name__ == "__main__":
    main()
